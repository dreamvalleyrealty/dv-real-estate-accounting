-- Paid commission corrections: append-only audit trail; never overwrite paid commission records.
create table if not exists public.dv_accounting_commission_corrections (
  id uuid primary key default gen_random_uuid(),
  correction_number bigint generated by default as identity unique,
  commission_id uuid not null references public.dv_accounting_commissions(id) on delete restrict,
  transaction_id uuid references public.dv_accounting_transactions(id) on delete restrict,
  agent_id uuid references public.dv_accounting_agents(id) on delete restrict,
  original_gross_commission numeric(14,2) not null,
  original_brokerage_share numeric(14,2) not null,
  original_agent_share numeric(14,2) not null,
  corrected_gross_commission numeric(14,2) not null,
  corrected_brokerage_share numeric(14,2) not null,
  corrected_agent_share numeric(14,2) not null,
  fee_adjustment numeric(14,2) not null default 0,
  agent_share_delta numeric(14,2) not null,
  reason text not null,
  notes text,
  status text not null default 'OPEN' check (status in ('OPEN','SETTLED','VOID')),
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  settled_by uuid,
  settled_at timestamptz,
  constraint dv_commission_correction_reason_not_blank check (length(trim(reason)) > 0)
);
create index if not exists idx_dv_commission_corrections_commission on public.dv_accounting_commission_corrections(commission_id, created_at desc);
alter table public.dv_accounting_commission_corrections enable row level security;
drop policy if exists dv_commission_corrections_management_read on public.dv_accounting_commission_corrections;
create policy dv_commission_corrections_management_read on public.dv_accounting_commission_corrections
 for select to authenticated using (
  exists (select 1 from public.dv_accounting_user_profiles p
          where p.user_id = auth.uid() and upper(coalesce(p.role,'')) in ('SUPERADMIN','ADMIN','MANAGER'))
 );
revoke insert, update, delete on public.dv_accounting_commission_corrections from anon, authenticated;
grant select on public.dv_accounting_commission_corrections to authenticated;
grant usage, select on sequence public.dv_accounting_commission_corrections_correction_number_seq to authenticated;

create or replace function public.dv_create_paid_commission_correction(
 p_commission_id uuid,
 p_corrected_gross_commission numeric,
 p_corrected_brokerage_share numeric,
 p_corrected_agent_share numeric,
 p_fee_adjustment numeric,
 p_reason text,
 p_notes text default null
) returns public.dv_accounting_commission_corrections
language plpgsql security definer set search_path=public as $$
declare c public.dv_accounting_commissions%rowtype;
        v_role text;
        v_result public.dv_accounting_commission_corrections%rowtype;
begin
 select upper(coalesce(role,'')) into v_role from public.dv_accounting_user_profiles where user_id=auth.uid() limit 1;
 if coalesce(v_role,'') not in ('SUPERADMIN','ADMIN','MANAGER') then raise exception 'Management permission required'; end if;
 select * into c from public.dv_accounting_commissions where id=p_commission_id for update;
 if not found then raise exception 'Commission record not found'; end if;
 if upper(coalesce(c.status,'')) <> 'PAID' then raise exception 'Only paid commissions can be corrected'; end if;
 if p_corrected_gross_commission < 0 or p_corrected_brokerage_share < 0 or p_corrected_agent_share < 0 then
   raise exception 'Corrected commission amounts cannot be negative';
 end if;
 if length(trim(coalesce(p_reason,'')))=0 then raise exception 'A correction reason is required'; end if;
 insert into public.dv_accounting_commission_corrections(
  commission_id, transaction_id, agent_id,
  original_gross_commission, original_brokerage_share, original_agent_share,
  corrected_gross_commission, corrected_brokerage_share, corrected_agent_share,
  fee_adjustment, agent_share_delta, reason, notes, created_by
 ) values (
  c.id,c.transaction_id,c.agent_id,
  coalesce(c.gross_commission,0),coalesce(c.brokerage_share,0),coalesce(c.agent_share,0),
  p_corrected_gross_commission,p_corrected_brokerage_share,p_corrected_agent_share,
  coalesce(p_fee_adjustment,0),p_corrected_agent_share-coalesce(c.agent_share,0)+coalesce(p_fee_adjustment,0),
  trim(p_reason),nullif(trim(coalesce(p_notes,'')),''),auth.uid()
 ) returning * into v_result;
 return v_result;
end $$;
revoke all on function public.dv_create_paid_commission_correction(uuid,numeric,numeric,numeric,numeric,text,text) from public;
grant execute on function public.dv_create_paid_commission_correction(uuid,numeric,numeric,numeric,numeric,text,text) to authenticated;
